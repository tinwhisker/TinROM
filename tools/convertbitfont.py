"""A 1bpp text-drawn font -> a C table.

    python3 tools/convertbitfont.py src/ui/fonts/term4x8.txt -o termfont.c

The input is the format src/ui/fonts/term4x8.txt describes: lines starting
with ";" are comments, ": <hex code>" starts a glyph, and the glyph's rows
follow, "#" for a lit pixel and "." for a clear one. Every glyph has the same
size, at most eight columns.

The output is `const uint8_t <name>[256][rows]`, one byte per row with the
leftmost column in bit (width - 1). A code with no glyph is left blank, and
the script says which. --first and --last cut it down to a range of codes,
which is then indexed from the first: the cart's crash screen carries only
the printable ASCII this way.

Standard library only, like the rest of the build.
"""

import argparse
import os
import sys


def die(message):
    print(f"convertbitfont: error: {message}", file=sys.stderr)
    sys.exit(1)


def read(path):
    glyphs, current, size = {}, None, None

    with open(path) as file:
        for number, raw in enumerate(file, 1):
            line = raw.rstrip("\r\n")

            if not line or line.startswith(";"):
                continue

            if line.startswith(":"):
                try:
                    current = int(line[1:].split()[0], 16)
                except (ValueError, IndexError):
                    die(f"{path}:{number}: expected ': <hex code>'")

                if not 0 <= current < 256:
                    die(f"{path}:{number}: code {current:#x} is out of range")
                if current in glyphs:
                    die(f"{path}:{number}: code {current:02X} drawn twice")

                glyphs[current] = []
                continue

            if current is None:
                die(f"{path}:{number}: a row before any ': <code>'")
            if set(line) - set("#."):
                die(f"{path}:{number}: rows are '#' and '.' only")

            glyphs[current].append(line)

    for code, rows in glyphs.items():
        shape = (len(rows[0]) if rows else 0, len(rows))

        if size is None:
            size = shape
        if shape != size or any(len(r) != size[0] for r in rows):
            die(f"glyph {code:02X} is {shape[0]}x{shape[1]}, the font is "
                f"{size[0]}x{size[1]}")

    if not size or size[0] > 8:
        die("glyphs must be one to eight columns wide")

    return glyphs, size


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("input")
    parser.add_argument("-o", "--output", required=True)
    parser.add_argument("--name", default="uiTermFont")
    parser.add_argument("--first", type=lambda text: int(text, 0), default=0,
        help="first code to include (default 0)")
    parser.add_argument("--last", type=lambda text: int(text, 0), default=255,
        help="last code to include (default 255)")
    args = parser.parse_args()

    if not 0 <= args.first <= args.last <= 255:
        die("--first and --last must be codes 0 to 255, first first")

    codes = range(args.first, args.last + 1)
    glyphs, (width, height) = read(args.input)
    missing = [code for code in codes if code not in glyphs]

    if missing:
        print("convertbitfont: blank: " + " ".join(f"{c:02X}" for c in missing))

    name = os.path.basename(args.input)
    out = [
        f"/* Generated by tools/convertbitfont.py from {name}. Do not edit:",
        " * change the font and rebuild. */",
        "",
        "#include <stdint.h>",
        "",
        f"const uint8_t {args.name}[{len(codes)}][{height}] = {{",
    ]

    for code in codes:
        rows = glyphs.get(code, ["." * width] * height)
        values = [
            sum(1 << (width - 1 - x) for x, c in enumerate(row) if c == "#")
            for row in rows
        ]
        label = chr(code) if 32 < code < 127 and chr(code) not in "\\/*" else ""
        out.append("\t{ " + ", ".join(f"0x{v:02x}" for v in values) + " },"
                   + (f" /* {label} */" if label else f" /* {code:02X} */"))

    out.append("};")

    with open(args.output, "w", newline="\n") as file:
        file.write("\n".join(out) + "\n")

    print(f"convertbitfont: {name} -> {len(codes)} glyphs, {width}x{height}")


if __name__ == "__main__":
    main()
